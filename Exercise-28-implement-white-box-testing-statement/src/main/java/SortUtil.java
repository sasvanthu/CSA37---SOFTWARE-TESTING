public class SortUtil {
    public static int[] bubbleSort(int[] a) {
        if (a == null) {
            throw new IllegalArgumentException("Array is null");
        }
        int n = a.length;
        for (int i = 0; i < n - 1; i++) {
            for (int j = 0; j < n - i - 1; j++) {
                if (a[j] > a[j + 1]) {
                    int temp = a[j];
                    a[j] = a[j + 1];
                    a[j + 1] = temp;
                }
            }
        }
        return a;
    }
}
